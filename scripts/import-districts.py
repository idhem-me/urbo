"""Import the supplied Urbo ZIP without executing its files or instructions."""
import json, re, sys, zipfile
from pathlib import Path, PurePosixPath
import xml.etree.ElementTree as ET

ROOT=Path(__file__).resolve().parents[1]
TYPES={'maison':'house','residence':'tower','boutiques-logements':'mixedShop','bureaux':'office','mairie':'townhall','pompiers':'fire','police':'police','ambulances':'ambulance','hopital':'hospital','charbon':'coal','solaire':'solar','carriere':'quarry','scierie':'sawmill','petrole':'oil','ferme':'farm','atelier':'workshop','petite-usine':'factory','grande-usine':'largeFactory','ecole':'school','parc':'park','stade':'stadium','foot':'football','tennis':'tennis','salle-sport':'gym','epicerie':'shop','supermarche':'supermarket','centre-commercial':'mall'}
ALLOWED={'svg','title','desc','g','polygon','path','rect','circle','ellipse','line','polyline'}

def inspect_svg(raw):
    if len(raw)>1_000_000 or b'<!DOCTYPE' in raw.upper() or b'<!ENTITY' in raw.upper():
        raise ValueError('SVG too large or contains XML declarations')
    root=ET.fromstring(raw)
    if root.tag!='{http://www.w3.org/2000/svg}svg':raise ValueError('Not SVG')
    for node in root.iter():
        if node.tag.split('}')[-1] not in ALLOWED:raise ValueError('Unsupported SVG element')
        for key,value in node.attrib.items():
            if key.lower().startswith('on') or 'href' in key.lower() or 'url(' in value.lower() or key=='style':
                raise ValueError('Active or external SVG content')
    x,y,w,h=map(float,root.attrib['viewBox'].split())
    if w<=0 or h<=0:raise ValueError('Invalid dimensions')
    return {'x':x,'y':y,'width':w,'height':h}

def main(path):
    records=[];files=[];keys=set()
    with zipfile.ZipFile(path) as archive:
        if sum(i.file_size for i in archive.infolist())>32_000_000:raise ValueError('Archive too large')
        for info in archive.infolist():
            if PurePosixPath(info.filename).is_absolute() or '..' in PurePosixPath(info.filename).parts:raise ValueError('Unsafe ZIP path')
            if not info.filename.endswith('.svg'):continue
            raw=archive.read(info);viewbox=inspect_svg(raw)
            match=re.fullmatch(r'(\d+)-quartier-(.+?)(?:-n([123]))?\.svg',PurePosixPath(info.filename).name)
            if not match:raise ValueError('Unknown filename '+info.filename)
            number,family,level=match.groups();kind='building' if family in TYPES else 'scenery'
            if kind=='scenery' and family not in ['construction','desert','foret']:raise ValueError('Unknown family')
            key=TYPES.get(family,{'construction':'construction','desert':'desert','foret':'forest'}.get(family));level=int(level or 1)
            dest=f'{key}/level-{level}'
            if dest in keys:raise ValueError('Duplicate mapping '+dest)
            keys.add(dest)
            metadata=json.loads(archive.read(info.filename[:-4]+'.json'))
            record={'id':int(number),'type':key,'level':level,'kind':kind,'label':metadata['name'],
                    'src':f'/assets/districts/{dest}.svg','source':info.filename,
                    'viewBox':viewbox,'ground':{'centerX':512,'centerY':288,'width':896,'height':448},
                    'footprint':{'columns':16,'rows':16},'bytes':len(raw)}
            records.append(record);files.extend([(dest+'.svg',raw),(dest+'.json',json.dumps(metadata,ensure_ascii=False,indent=2).encode())])
    if len(records)!=61:raise ValueError('Expected 61 SVG files')
    # Write only after the whole package passes validation.
    for name,data in files:
        target=ROOT/'public/assets/districts'/name;target.parent.mkdir(parents=True,exist_ok=True);target.write_bytes(data)
    records.sort(key=lambda r:r['id'])
    (ROOT/'src/assets/districts.js').write_text('// Generated by scripts/import-districts.py. Preserve original SVGs.\nexport const DISTRICT_ASSETS='+json.dumps(records,ensure_ascii=False,indent=2)+';\n')
    print(f'Imported {len(records)} assets, {sum(r["bytes"] for r in records)} SVG bytes')

if __name__=='__main__':main(sys.argv[1])
